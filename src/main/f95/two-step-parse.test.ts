import { describe, expect, test } from 'bun:test'
import { parseTwoStepError, parseTwoStepForm } from './two-step-parse'

const PAGE_URL = 'https://f95zone.to/login/two-step?_xfRedirect=%2F&remember=1'

const TOTP_PAGE = `
<div class="p-body-pageContent">
  <form action="/login/two-step" method="post" class="block">
    <div class="block-container">
      <div class="block-body">
        <dl class="formRow formRow--input">
          <dt><div class="formRow-labelWrapper"><label class="formRow-label">Verification code</label></div></dt>
          <dd>
            <input type="text" class="input" name="code" autocomplete="one-time-code" />
            <div class="formRow-explain">Please enter the verification code generated by the app on your phone.</div>
          </dd>
        </dl>
        <dl class="formRow">
          <dd>
            <ul class="inputChoices">
              <li><label class="iconic"><input type="checkbox" name="trust" value="1" /><span class="iconic-label">Don't ask again on this computer for 30 days</span></label></li>
            </ul>
          </dd>
        </dl>
      </div>
      <dl class="formRow formSubmitRow"><dd><button type="submit" class="button--primary button">Confirm</button></dd></dl>
      <div class="block-footer">
        <span class="block-footer-controls">
          <a href="/login/two-step?provider=email&amp;_xfRedirect=%2F&amp;remember=1">Email confirmation</a>
          <a href="/login/two-step?provider=backup&amp;_xfRedirect=%2F&amp;remember=1">Backup codes</a>
          <a href="/login/two-step?provider=totp&amp;_xfRedirect=%2F&amp;remember=1">Verification code via app</a>
        </span>
      </div>
    </div>
    <input type="hidden" name="provider" value="totp" />
    <input type="hidden" name="remember" value="1" />
    <input type="hidden" name="_xfRedirect" value="/" />
    <input type="hidden" name="_xfToken" value="1730000000,abcdef" />
  </form>
</div>
`

const EMAIL_PAGE = `
<form action="https://f95zone.to/login/two-step" method="post">
  <div class="block-body">
    <div class="formInfoRow">An email has been sent to p***@example.com with a code.</div>
    <dl class="formRow"><dd><input type="text" name="code" /></dd></dl>
  </div>
  <input type="hidden" name="provider" value="email" />
  <input type="hidden" name="_xfToken" value="tok" />
</form>
`

const ERROR_PAGE = `
<div class="p-body-pageContent">
  <div class="blockMessage">The two-step verification value could not be confirmed. Please try again.</div>
</div>
`

describe('parseTwoStepForm', () => {
  test('reads the XenForo two-step form with hidden fields and alternatives', () => {
    const form = parseTwoStepForm(TOTP_PAGE, PAGE_URL)
    expect(form).not.toBeNull()
    expect(form!.action).toBe('https://f95zone.to/login/two-step')
    expect(form!.provider).toBe('totp')
    expect(form!.canTrust).toBe(true)
    expect(form!.fields).toEqual([
      ['provider', 'totp'],
      ['remember', '1'],
      ['_xfRedirect', '/'],
      ['_xfToken', '1730000000,abcdef']
    ])
    expect(form!.prompt).toBe('Please enter the verification code generated by the app on your phone.')
    expect(form!.providers.map(({ id, label }) => ({ id, label }))).toEqual([
      { id: 'email', label: 'Email confirmation' },
      { id: 'backup', label: 'Backup codes' }
    ])
    expect(form!.providers[0].href).toBe(
      'https://f95zone.to/login/two-step?provider=email&_xfRedirect=%2F&remember=1'
    )
  })

  test('reads info rows as the prompt and handles a form without trust', () => {
    const form = parseTwoStepForm(EMAIL_PAGE, PAGE_URL)
    expect(form!.provider).toBe('email')
    expect(form!.canTrust).toBe(false)
    expect(form!.prompt).toBe('An email has been sent to p***@example.com with a code.')
    expect(form!.providers).toEqual([])
  })

  test('returns null for pages without a two-step form', () => {
    expect(parseTwoStepForm('<form action="/login/login"><input name="login" /></form>', PAGE_URL)).toBeNull()
    expect(parseTwoStepForm(ERROR_PAGE, PAGE_URL)).toBeNull()
  })
})

describe('parseTwoStepError', () => {
  test('reads a standalone XenForo error page', () => {
    expect(parseTwoStepError(ERROR_PAGE)).toBe(
      'The two-step verification value could not be confirmed. Please try again.'
    )
  })

  test('prefers inline error blocks and joins list items', () => {
    const html = `
      <div class="blockMessage">Notice</div>
      <div class="blockMessage blockMessage--error"><ul><li>Too many attempts.</li><li>Wait a moment.</li></ul></div>`
    expect(parseTwoStepError(html)).toBe('Too many attempts. Wait a moment.')
  })

  test('returns null when there is no message', () => {
    expect(parseTwoStepError('<html><body></body></html>')).toBeNull()
  })
})
